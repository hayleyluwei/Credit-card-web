import { existsSync, mkdirSync, copyFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { PrismaClient } from "@prisma/client";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(__dirname, "..");

const DEFAULT_XLSX = path.join(
  projectRoot,
  "docs/data-collection/信用卡優惠資料整理模板-v2-2026-07-18.xlsx"
);

const VALID_CATEGORIES = ["cashback", "dining", "travel", "online-shopping", "transport", "installment"];
const REWARD_TYPE_MAP = {
  "現金回饋": "cashback",
  "點數回饋": "points",
  "折扣": "discount",
  "分期": "installment",
  "其他": "other"
};

const args = process.argv.slice(2);
const isDryRun = args.includes("--dry-run");
const isReset = args.includes("--reset");
const xlsxPathArg = args.find((a) => !a.startsWith("--"));
const xlsxPath = xlsxPathArg ? path.resolve(xlsxPathArg) : DEFAULT_XLSX;

function readWorkbook(filePath) {
  const pyScript = `
import openpyxl, json, sys
wb = openpyxl.load_workbook(sys.argv[1], data_only=True)
out = {}
for name in ["banks", "cards", "offers", "offer_cards"]:
    ws = wb[name]
    rows = [list(r) for r in ws.iter_rows(values_only=True)]
    out[name] = rows
print(json.dumps(out, ensure_ascii=False))
`;
  const stdout = execFileSync("python", ["-c", pyScript, filePath], {
    encoding: "utf-8",
    maxBuffer: 20 * 1024 * 1024,
    env: { ...process.env, PYTHONIOENCODING: "utf-8" }
  });
  return JSON.parse(stdout);
}

function rowsToObjects(rows) {
  const [header, ...dataRows] = rows;
  return dataRows
    .filter((row) => row.some((cell) => cell !== null && cell !== ""))
    .map((row) => {
      const obj = {};
      header.forEach((key, i) => {
        obj[key] = row[i] === undefined ? null : row[i];
      });
      return obj;
    });
}

function isBlank(v) {
  return v === null || v === undefined || String(v).trim() === "";
}

function isValidDate(v) {
  return typeof v === "string" && /^\d{4}-\d{2}-\d{2}$/.test(v) && !Number.isNaN(new Date(v).getTime());
}

let autoSlugCounter = 0;
function autoSlug(title) {
  autoSlugCounter += 1;
  const base = String(title)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
  return (base || "offer") + "-auto-" + autoSlugCounter;
}

function validate(banks, cards, offers, offerCards, existingBankSlugs = new Set(), existingCardSlugs = new Set()) {
  const errors = [];
  const warnings = [];
  const autoGeneratedSlugs = [];

  const bankCodes = new Set();
  banks.forEach((b, i) => {
    const row = i + 2;
    if (isBlank(b["銀行名稱＊"])) errors.push(`banks 第${row}列：銀行名稱為必填`);
    if (isBlank(b["銀行代號＊"])) errors.push(`banks 第${row}列：銀行代號為必填`);
    else if (bankCodes.has(b["銀行代號＊"])) errors.push(`banks 第${row}列：銀行代號「${b["銀行代號＊"]}」重複`);
    else bankCodes.add(b["銀行代號＊"]);
    if (isBlank(b["官網網址＊"])) errors.push(`banks 第${row}列：官網網址為必填`);
  });

  const cardCodes = new Set();
  cards.forEach((c, i) => {
    const row = i + 2;
    if (isBlank(c["卡片名稱＊"])) errors.push(`cards 第${row}列：卡片名稱為必填`);
    if (isBlank(c["卡片代號＊"])) errors.push(`cards 第${row}列：卡片代號為必填`);
    else if (cardCodes.has(c["卡片代號＊"])) errors.push(`cards 第${row}列：卡片代號「${c["卡片代號＊"]}」重複`);
    else cardCodes.add(c["卡片代號＊"]);
    if (isBlank(c["所屬銀行代號＊"])) errors.push(`cards 第${row}列：所屬銀行代號為必填`);
    else if (!bankCodes.has(c["所屬銀行代號＊"]) && !existingBankSlugs.has(c["所屬銀行代號＊"])) {
      errors.push(`cards 第${row}列：所屬銀行代號「${c["所屬銀行代號＊"]}」在 banks 工作表與現有資料庫都找不到對應（增量模式下，引用既有銀行不需要在本次表格重複列出該銀行，但代號要正確存在）`);
    }
    if (isBlank(c["卡片官方頁面網址＊"])) errors.push(`cards 第${row}列：卡片官方頁面網址為必填`);
    if (isBlank(c["一句話摘要＊"])) errors.push(`cards 第${row}列：一句話摘要為必填`);
  });

  const offerCodes = new Set();
  offers.forEach((o, i) => {
    const row = i + 2;
    let slug = o["優惠代號＊"];
    if (isBlank(slug)) {
      slug = autoSlug(o["優惠標題＊"] ?? "offer");
      o["優惠代號＊"] = slug;
      autoGeneratedSlugs.push({ row, title: o["優惠標題＊"], slug });
    } else if (offerCodes.has(slug)) {
      errors.push(`offers 第${row}列：優惠代號「${slug}」重複`);
    }
    offerCodes.add(slug);

    if (isBlank(o["優惠標題＊"])) errors.push(`offers 第${row}列：優惠標題為必填`);
    if (isBlank(o["主分類代碼＊"])) errors.push(`offers 第${row}列：主分類代碼為必填`);
    else if (!VALID_CATEGORIES.includes(o["主分類代碼＊"])) errors.push(`offers 第${row}列：主分類代碼「${o["主分類代碼＊"]}」不屬於六個合法值`);
    if (isBlank(o["一句話摘要＊"])) errors.push(`offers 第${row}列：一句話摘要為必填`);
    if (isBlank(o["詳細說明＊"])) errors.push(`offers 第${row}列：詳細說明為必填`);
    if (isBlank(o["回饋類型＊"])) errors.push(`offers 第${row}列：回饋類型為必填`);
    else if (!(o["回饋類型＊"] in REWARD_TYPE_MAP)) errors.push(`offers 第${row}列：回饋類型「${o["回饋類型＊"]}」不屬於五個合法值`);
    if (isBlank(o["回饋數值＊"])) errors.push(`offers 第${row}列：回饋數值為必填`);
    if (isBlank(o["條件與限制＊"])) errors.push(`offers 第${row}列：條件與限制為必填`);
    if (isBlank(o["來源網址＊"])) errors.push(`offers 第${row}列：來源網址為必填`);
    if (isBlank(o["查證日期＊"])) errors.push(`offers 第${row}列：查證日期為必填`);
    else if (!isValidDate(o["查證日期＊"])) errors.push(`offers 第${row}列：查證日期格式須為 YYYY-MM-DD`);

    const start = o["開始日期"];
    const end = o["結束日期"];
    if (!isBlank(start) && !isValidDate(start)) errors.push(`offers 第${row}列：開始日期格式須為 YYYY-MM-DD`);
    if (!isBlank(end) && !isValidDate(end)) errors.push(`offers 第${row}列：結束日期格式須為 YYYY-MM-DD`);
    if (!isBlank(start) && !isBlank(end) && isValidDate(start) && isValidDate(end) && end < start) {
      errors.push(`offers 第${row}列：結束日期早於開始日期`);
    }

    if (!isBlank(o["最低消費"]) && String(o["最低消費"]).length > 60 && /[。\n]/.test(String(o["最低消費"]))) {
      warnings.push(`offers 第${row}列（${slug}）：最低消費欄位內容偏長、疑似寫入了條件說明而非門檻金額，建議人工核對`);
    }
  });

  const offerCodesFinal = new Set(offers.map((o) => o["優惠代號＊"]));
  offerCards.forEach((oc, i) => {
    const row = i + 2;
    if (isBlank(oc["優惠代號＊"])) errors.push(`offer_cards 第${row}列：優惠代號為必填`);
    else if (!offerCodesFinal.has(oc["優惠代號＊"])) errors.push(`offer_cards 第${row}列：優惠代號「${oc["優惠代號＊"]}」在 offers 找不到對應`);
    if (isBlank(oc["卡片代號＊"])) errors.push(`offer_cards 第${row}列：卡片代號為必填`);
    else if (!cardCodes.has(oc["卡片代號＊"]) && !existingCardSlugs.has(oc["卡片代號＊"])) {
      errors.push(`offer_cards 第${row}列：卡片代號「${oc["卡片代號＊"]}」在 cards 工作表與現有資料庫都找不到對應（增量模式下，引用既有卡片不需要在本次表格重複列出該卡片，但代號要正確存在）`);
    }
  });

  const coveredOffers = new Set(offerCards.map((oc) => oc["優惠代號＊"]));
  offers.forEach((o, i) => {
    const row = i + 2;
    if (!coveredOffers.has(o["優惠代號＊"])) errors.push(`offers 第${row}列（${o["優惠代號＊"]}）：在 offer_cards 沒有任何對應卡片`);
  });

  return { errors, warnings, autoGeneratedSlugs };
}

async function main() {
  if (!existsSync(xlsxPath)) {
    console.error(`找不到試算表檔案：${xlsxPath}`);
    process.exit(1);
  }

  console.log(`讀取試算表：${xlsxPath}`);
  const wb = readWorkbook(xlsxPath);
  const banks = rowsToObjects(wb.banks);
  const cards = rowsToObjects(wb.cards);
  const offers = rowsToObjects(wb.offers);
  const offerCards = rowsToObjects(wb.offer_cards);

  console.log(`筆數：banks=${banks.length} cards=${cards.length} offers=${offers.length} offer_cards=${offerCards.length}`);

  // 增量模式下，本次表格可以不重複列出既有銀行/卡片，所以驗證時也要承認資料庫既有的代號。
  // --reset 模式會整批清空重建，既有代號全部作廢，只能引用本次表格內的代號。
  let existingBankSlugs = new Set();
  let existingCardSlugs = new Set();
  if (!isReset) {
    const lookupPrisma = new PrismaClient();
    try {
      const [existingBanks, existingCards] = await Promise.all([
        lookupPrisma.bank.findMany({ select: { slug: true } }),
        lookupPrisma.card.findMany({ select: { slug: true } })
      ]);
      existingBankSlugs = new Set(existingBanks.map((b) => b.slug));
      existingCardSlugs = new Set(existingCards.map((c) => c.slug));
    } finally {
      await lookupPrisma.$disconnect();
    }
  }

  const { errors, warnings, autoGeneratedSlugs } = validate(banks, cards, offers, offerCards, existingBankSlugs, existingCardSlugs);

  console.log("\n=== 檢查報告 ===");
  if (errors.length === 0) {
    console.log("錯誤：0");
  } else {
    console.log(`錯誤：${errors.length}`);
    errors.forEach((e) => console.log("  [ERROR] " + e));
  }
  if (warnings.length > 0) {
    console.log(`警告：${warnings.length}`);
    warnings.forEach((w) => console.log("  [WARN] " + w));
  }
  if (autoGeneratedSlugs.length > 0) {
    console.log("自動產生的優惠代號：");
    autoGeneratedSlugs.forEach((s) => console.log(`  第${s.row}列「${s.title}」→ ${s.slug}`));
  }

  if (errors.length > 0) {
    console.error("\n檢查未通過，不會寫入資料庫。");
    process.exit(1);
  }

  if (isDryRun) {
    console.log(`\n--dry-run 模式：檢查通過，未寫入資料庫。（匯入模式：${isReset ? "整批清空重建 --reset" : "增量更新（預設）"}）`);
    return;
  }

  const backupDir = path.join(projectRoot, "prisma/backups");
  if (!existsSync(backupDir)) mkdirSync(backupDir, { recursive: true });
  const stamp = new Date().toISOString().replace(/[-:]/g, "").replace(/\..+/, "").replace("T", "-");
  const backupPath = path.join(backupDir, `dev-before-import-${isReset ? "reset" : "upsert"}-${stamp}.db`);
  copyFileSync(path.join(projectRoot, "prisma/dev.db"), backupPath);
  console.log(`\n已備份 dev.db 至：${backupPath}`);

  const prisma = new PrismaClient();
  try {
    if (isReset) {
      await runReset(prisma, { banks, cards, offers, offerCards });
    } else {
      await runUpsert(prisma, { banks, cards, offers, offerCards });
    }
    console.log("\n匯入完成。");
  } finally {
    await prisma.$disconnect();
  }
}

function cardJsonFields(c) {
  const prosJson = c["優點"] ? JSON.stringify(String(c["優點"]).split("\n").map((s) => s.trim()).filter(Boolean)) : null;
  const consJson = c["注意事項"] ? JSON.stringify(String(c["注意事項"]).split("\n").map((s) => s.trim()).filter(Boolean)) : null;
  return { prosJson, consJson };
}

function offerData(o, categoryId) {
  return {
    categoryId,
    title: o["優惠標題＊"],
    summary: o["一句話摘要＊"] || null,
    targetAudience: o["適合對象"] || null,
    highlight1: o["亮點一"] || null,
    highlight2: o["亮點二"] || null,
    description: o["詳細說明＊"] || null,
    startDate: o["開始日期"] ? new Date(`${o["開始日期"]}T00:00:00+08:00`) : null,
    endDate: o["結束日期"] ? new Date(`${o["結束日期"]}T00:00:00+08:00`) : null,
    // [T21] 非正規化摘要欄位；扁平回饋欄位已移至 RewardTier（見 tierDataFromRow）。
    headlineRate: o["回饋數值＊"] || null,
    sourceUrl: o["來源網址＊"] || null,
    lastVerifiedAt: new Date(`${o["查證日期＊"]}T00:00:00+08:00`),
    tags: o["標籤"] || null,
    seoTitle: `${o["優惠標題＊"]}｜信用卡優惠`,
    seoDescription: o["一句話摘要＊"] || null
  };
}

// [T21] 試算表 offers 工作表目前仍是扁平（一檔一組回饋），因此每筆優惠對應建立一層 RewardTier。
// 多層結構化優惠（如幣倍卡）目前透過後台 tier 表單或 seed 手動建立；試算表多層寫法待規格 v3+ 再議。
function tierDataFromRow(o) {
  return {
    label: null,
    rewardType: REWARD_TYPE_MAP[o["回饋類型＊"]] || null,
    rate: o["回饋數值＊"] || null,
    cap: o["回饋上限"] || null,
    capPeriod: null,
    minSpend: o["最低消費"] || null,
    conditionsText: o["條件與限制＊"] || null,
    conditions: null,
    sortOrder: 0
  };
}

// 整批清空重建（--reset）：僅供需要整批重來時使用（例如當年 T16 seed→真實資料轉換）。
// 會清除全部既有 Bank/Card/Offer/OfferCard，不保留任何未列在本次試算表的既有資料。
async function runReset(prisma, { banks, cards, offers, offerCards }) {
  console.log("[--reset 模式] 清除既有 Offer / OfferCard / Card / Bank（保留 Category / SiteSetting / AdminUser）...");
  await prisma.offerCard.deleteMany({});
  await prisma.offer.deleteMany({});
  await prisma.card.deleteMany({});
  await prisma.bank.deleteMany({});

  const bankIdBySlug = {};
  for (const b of banks) {
    const created = await prisma.bank.create({
      data: {
        name: b["銀行名稱＊"],
        slug: b["銀行代號＊"],
        websiteUrl: b["官網網址＊"],
        logoUrl: b["Logo 圖片網址"] || null,
        description: b["簡介"] || null,
        isActive: true
      }
    });
    bankIdBySlug[b["銀行代號＊"]] = created.id;
  }
  console.log(`已寫入 ${banks.length} 筆銀行`);

  const cardIdBySlug = {};
  for (const c of cards) {
    const { prosJson, consJson } = cardJsonFields(c);
    const created = await prisma.card.create({
      data: {
        bankId: bankIdBySlug[c["所屬銀行代號＊"]],
        name: c["卡片名稱＊"],
        slug: c["卡片代號＊"],
        imageUrl: c["卡面圖片網址"] || null,
        summary: c["一句話摘要＊"] || null,
        description: c["詳細說明"] || null,
        targetAudience: c["適合對象"] || null,
        annualFee: c["年費"] || null,
        annualFeeWaiver: c["免年費條件"] || null,
        cardLevel: c["卡片等級"] || null,
        cardNetwork: c["發卡組織"] || null,
        prosJson,
        consJson,
        isActive: true
      }
    });
    cardIdBySlug[c["卡片代號＊"]] = created.id;
  }
  console.log(`已寫入 ${cards.length} 筆卡片`);

  const categoryIdBySlug = {};
  (await prisma.category.findMany()).forEach((cat) => {
    categoryIdBySlug[cat.slug] = cat.id;
  });

  const offerIdBySlug = {};
  for (const o of offers) {
    const created = await prisma.offer.create({
      data: {
        ...offerData(o, categoryIdBySlug[o["主分類代碼＊"]]),
        slug: o["優惠代號＊"],
        isFeatured: false,
        recommendScore: 50,
        sortOrder: 0,
        isPublished: true,
        tiers: { create: [tierDataFromRow(o)] }
      }
    });
    offerIdBySlug[o["優惠代號＊"]] = created.id;
  }
  console.log(`已寫入 ${offers.length} 筆優惠（各含 1 層 RewardTier）`);

  for (const oc of offerCards) {
    await prisma.offerCard.create({
      data: {
        offerId: offerIdBySlug[oc["優惠代號＊"]],
        cardId: cardIdBySlug[oc["卡片代號＊"]]
      }
    });
  }
  console.log(`已寫入 ${offerCards.length} 筆優惠與卡片對應`);
}

// 增量更新（預設）：以 slug 比對，存在就整列覆蓋更新、不存在就新增；
// 完全不刪除本次試算表沒有列出的既有 Bank/Card/Offer。
// offer_cards 只針對「本次試算表有出現的優惠」同步其卡片對應（先清除該優惠既有對應，
// 再依表格內容重建），未出現在本次表格的優惠，其既有對應完全不受影響。
async function runUpsert(prisma, { banks, cards, offers, offerCards }) {
  console.log("[增量更新模式] 依 slug 比對，既有資料整列覆蓋、新資料新增，未列出的既有資料不受影響...");

  const bankIdBySlug = {};
  let bankCreated = 0;
  let bankUpdated = 0;
  for (const b of banks) {
    const slug = b["銀行代號＊"];
    const data = {
      name: b["銀行名稱＊"],
      slug,
      websiteUrl: b["官網網址＊"],
      logoUrl: b["Logo 圖片網址"] || null,
      description: b["簡介"] || null
    };
    const existing = await prisma.bank.findUnique({ where: { slug } });
    const result = await prisma.bank.upsert({
      where: { slug },
      create: { ...data, isActive: true },
      update: data
    });
    bankIdBySlug[slug] = result.id;
    if (existing) bankUpdated += 1;
    else bankCreated += 1;
  }
  console.log(`銀行：新增 ${bankCreated}／更新 ${bankUpdated}`);

  // 已存在但這次表格沒提到、卡片引用到的銀行代號，直接沿用資料庫既有資料。
  for (const c of cards) {
    const bslug = c["所屬銀行代號＊"];
    if (!bankIdBySlug[bslug]) {
      const existingBank = await prisma.bank.findUnique({ where: { slug: bslug } });
      if (existingBank) bankIdBySlug[bslug] = existingBank.id;
    }
  }

  const cardIdBySlug = {};
  let cardCreated = 0;
  let cardUpdated = 0;
  for (const c of cards) {
    const slug = c["卡片代號＊"];
    const { prosJson, consJson } = cardJsonFields(c);
    const data = {
      bankId: bankIdBySlug[c["所屬銀行代號＊"]],
      name: c["卡片名稱＊"],
      slug,
      imageUrl: c["卡面圖片網址"] || null,
      summary: c["一句話摘要＊"] || null,
      description: c["詳細說明"] || null,
      targetAudience: c["適合對象"] || null,
      annualFee: c["年費"] || null,
      annualFeeWaiver: c["免年費條件"] || null,
      cardLevel: c["卡片等級"] || null,
      cardNetwork: c["發卡組織"] || null,
      prosJson,
      consJson
    };
    const existing = await prisma.card.findUnique({ where: { slug } });
    const result = await prisma.card.upsert({
      where: { slug },
      create: { ...data, isActive: true },
      update: data
    });
    cardIdBySlug[slug] = result.id;
    if (existing) cardUpdated += 1;
    else cardCreated += 1;
  }
  console.log(`卡片：新增 ${cardCreated}／更新 ${cardUpdated}`);

  for (const oc of offerCards) {
    const cslug = oc["卡片代號＊"];
    if (!cardIdBySlug[cslug]) {
      const existingCard = await prisma.card.findUnique({ where: { slug: cslug } });
      if (existingCard) cardIdBySlug[cslug] = existingCard.id;
    }
  }

  const categoryIdBySlug = {};
  (await prisma.category.findMany()).forEach((cat) => {
    categoryIdBySlug[cat.slug] = cat.id;
  });

  const offerIdBySlug = {};
  let offerCreated = 0;
  let offerUpdated = 0;
  for (const o of offers) {
    const slug = o["優惠代號＊"];
    const data = offerData(o, categoryIdBySlug[o["主分類代碼＊"]]);
    const existing = await prisma.offer.findUnique({ where: { slug } });
    const result = await prisma.offer.upsert({
      where: { slug },
      create: {
        ...data,
        slug,
        isFeatured: false,
        recommendScore: 50,
        sortOrder: 0,
        isPublished: true
      },
      update: data
    });
    offerIdBySlug[slug] = result.id;
    // [T21] 重建這筆優惠的 RewardTier（試算表為扁平，對應一層）。先清後建以免重複。
    await prisma.rewardTier.deleteMany({ where: { offerId: result.id } });
    await prisma.rewardTier.create({ data: { ...tierDataFromRow(o), offerId: result.id } });
    if (existing) offerUpdated += 1;
    else offerCreated += 1;
  }
  console.log(`優惠：新增 ${offerCreated}／更新 ${offerUpdated}（各重建 1 層 RewardTier；未列在本次表格的既有優惠不受影響）`);

  const touchedOfferSlugs = [...new Set(offers.map((o) => o["優惠代號＊"]))];
  for (const slug of touchedOfferSlugs) {
    const offerId = offerIdBySlug[slug];
    if (offerId) await prisma.offerCard.deleteMany({ where: { offerId } });
  }
  let offerCardCreated = 0;
  for (const oc of offerCards) {
    const offerId = offerIdBySlug[oc["優惠代號＊"]];
    const cardId = cardIdBySlug[oc["卡片代號＊"]];
    if (offerId && cardId) {
      await prisma.offerCard.create({ data: { offerId, cardId } });
      offerCardCreated += 1;
    }
  }
  console.log(`優惠與卡片對應：本次同步 ${offerCardCreated} 筆（僅針對本次表格出現的優惠重建對應，其餘既有優惠的對應不受影響）`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
